"""Train and tune BCC-CSM2-MR XGBoost models for lightning and hail frequency.

This script is adapted from the author's final checked BCC-CSM2-MR notebook.
It uses the historical feature parquet generated by ``bcc_01_build_features.py``
and performs:

- removal of seasonal features from the training candidate set;
- a fixed 70/15/15 random train/validation/test split;
- full-feature gain ranking;
- TopK feature-number sensitivity tests;
- XGBoost hyperparameter sensitivity tests;
- separate final models for lightning (legacy internal name ``FLASH``) and hail.

Run from the repository root with::

    python -m modeling.bcc_02_train
"""

