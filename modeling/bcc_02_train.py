def rmse(y_true, y_pred):
    return np.sqrt(mean_squared_error(y_true, y_pred))


def metrics_dict(y_true, y_pred):
    return {
        "r2": float(r2_score(y_true, y_pred)),
        "rmse": float(rmse(y_true, y_pred)),
        "mae": float(mean_absolute_error(y_true, y_pred)),
        "n": int(len(y_true)),
    }


def safe_mkdir(path: str | Path):
    Path(path).mkdir(parents=True, exist_ok=True)


def timestamp():
    return time.strftime("%Y%m%d_%H%M%S")


def file_exists_or_raise(path: str | Path, what: str):
    if not Path(path).exists():
        raise FileNotFoundError(f"{what} not found: {path}")


def choose_feature_columns(df: pd.DataFrame) -> list[str]:
    """Keep annual ``env_*`` features and ``elev``; exclude seasonal features."""
    out = []
    for c in df.columns:
        if c == "elev":
            out.append(c)
            continue
        if not str(c).startswith("env_"):
            continue
        if any(tag in c for tag in ("_DJF_", "_MAM_", "_JJA_", "_SON_")):
            continue
        out.append(c)
    return sorted(out)


def get_best_iteration(model: xgb.Booster) -> int:
    """Return zero-based best iteration with compatibility handling."""
    best_iter = getattr(model, "best_iteration", None)
    if best_iter is not None:
        return int(best_iter)
    return int(model.num_boosted_rounds() - 1)


def predict_with_best(model: xgb.Booster, dmat: xgb.DMatrix) -> np.ndarray:
    """Predict using the best iteration, compatible with common XGBoost versions."""
    best_iter = get_best_iteration(model)
    try:
        return model.predict(dmat, iteration_range=(0, best_iter + 1))
    except TypeError:
        best_ntree_limit = getattr(model, "best_ntree_limit", None)
        if best_ntree_limit is not None and best_ntree_limit > 0:
            return model.predict(dmat, ntree_limit=best_ntree_limit)
        return model.predict(dmat)


def make_param_combinations(param_grid: dict) -> list[dict]:
    keys = list(param_grid.keys())
    vals = [param_grid[k] for k in keys]
    return [dict(zip(keys, one)) for one in itertools.product(*vals)]


def normalize_topk_list(topk_list: list, n_features: int) -> list[tuple[str, int]]:
    """Convert requested TopK values into unique, valid feature counts."""
    out = []
    seen_k = set()

    for item in topk_list:
        if isinstance(item, str) and item.lower() == "all":
            k = n_features
            label = "All"
        else:
            requested = int(item)
            k = min(requested, n_features)
            label = f"Top{requested}" if requested <= n_features else f"Top{requested}_actual{k}"

        if k <= 0 or k in seen_k:
            continue
        seen_k.add(k)
        out.append((label, k))

    if not out:
        out = [("All", n_features)]
    return out


