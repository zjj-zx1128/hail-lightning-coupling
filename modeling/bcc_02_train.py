def main():
    print("=" * 80)
    print("BCC-CSM2-MR XGBoost training (non-seasonal features)")
    print("=" * 80)
    print(f"[FEATURE_HIST] {FEATURE_HIST}")
    print(f"[LABEL_STRICT] {LABEL_STRICT}")
    print(f"[OUT_ROOT] {RUN_ROOT}")
    print(f"[RUN_SENSITIVITY_TEST] {RUN_SENSITIVITY_TEST}")
    print(f"[RUN_TOPK_TEST] {RUN_TOPK_TEST}")
    print(f"[TOPK_LIST] {TOPK_LIST}")

    run_id = timestamp()
    summary_rows = []

    run_flash = RUN_ROOT / f"FLASH_{run_id}"
    df_flash, feat_cols_flash_all = load_train_table(
        FEATURE_HIST, LABEL_STRICT, TARGET_FLASH
    )
    _, metrics_flash, _ = train_one_target(
        df=df_flash,
        all_feature_cols=feat_cols_flash_all,
        target_col=TARGET_FLASH,
        out_dir=run_flash,
    )
    summary_rows.append(
        {
            "target": TARGET_FLASH,
            "run_dir": str(run_flash),
            "n_all_features": metrics_flash["n_all_features"],
            "selected_topk_label": metrics_flash["selected_topk_label"],
            "selected_topk_n": metrics_flash["selected_topk_n"],
            "n_features": metrics_flash["n_features"],
            "best_iteration": metrics_flash["best_iteration"],
            "train_r2": metrics_flash["train"]["r2"],
            "valid_r2": metrics_flash["valid"]["r2"],
            "test_r2": metrics_flash["test"]["r2"],
            "train_rmse": metrics_flash["train"]["rmse"],
            "valid_rmse": metrics_flash["valid"]["rmse"],
            "test_rmse": metrics_flash["test"]["rmse"],
        }
    )

    run_hail = RUN_ROOT / f"HAIL_{run_id}"
    df_hail, feat_cols_hail_all = load_train_table(
        FEATURE_HIST, LABEL_STRICT, TARGET_HAIL
    )
    _, metrics_hail, _ = train_one_target(
        df=df_hail,
        all_feature_cols=feat_cols_hail_all,
        target_col=TARGET_HAIL,
        out_dir=run_hail,
    )
    summary_rows.append(
        {
            "target": TARGET_HAIL,
            "run_dir": str(run_hail),
            "n_all_features": metrics_hail["n_all_features"],
            "selected_topk_label": metrics_hail["selected_topk_label"],
            "selected_topk_n": metrics_hail["selected_topk_n"],
            "n_features": metrics_hail["n_features"],
            "best_iteration": metrics_hail["best_iteration"],
            "train_r2": metrics_hail["train"]["r2"],
            "valid_r2": metrics_hail["valid"]["r2"],
            "test_r2": metrics_hail["test"]["r2"],
            "train_rmse": metrics_hail["train"]["rmse"],
            "valid_rmse": metrics_hail["valid"]["rmse"],
            "test_rmse": metrics_hail["test"]["rmse"],
        }
    )

    df_summary = pd.DataFrame(summary_rows)
    summary_csv = RUN_ROOT / f"summary_FLASH_HAIL_{run_id}.csv"
    df_summary.to_csv(summary_csv, index=False, encoding="utf-8-sig")

    print("\n" + "=" * 80)
    print("[DONE] BCC-CSM2-MR training and TopK sensitivity finished.")
    print(f"[SUMMARY] {summary_csv}")
    print(f"[OUT] {RUN_ROOT}")
    print("=" * 80)


if __name__ == "__main__":
    main()
