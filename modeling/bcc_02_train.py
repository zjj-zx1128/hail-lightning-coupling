def load_train_table(feature_hist: str | Path, label_strict: str | Path, target_col: str):
    file_exists_or_raise(feature_hist, "historical feature parquet")
    file_exists_or_raise(label_strict, "strict-land label parquet")

    df_feat = pd.read_parquet(feature_hist)
    df_lab = pd.read_parquet(label_strict)

    need_cols = [LAT_COL, LON_COL, target_col]
    missing_lab = [c for c in need_cols if c not in df_lab.columns]
    if missing_lab:
        raise ValueError(f"label_strict is missing columns: {missing_lab}")
    df_lab = df_lab[need_cols].copy()

    df = df_lab.merge(df_feat, on=[LAT_COL, LON_COL], how="inner")

    feat_cols = choose_feature_columns(df)
    if not feat_cols:
        raise ValueError("No candidate env_* or elev features were found.")

    keep_cols = [LAT_COL, LON_COL, target_col] + feat_cols
    df = df[keep_cols].copy().replace([np.inf, -np.inf], np.nan)

    before = len(df)
    df = df.dropna(subset=[target_col] + feat_cols).reset_index(drop=True)
    after = len(df)

    print(f"[{target_col}] merged rows   : {before}")
    print(f"[{target_col}] rows after NA : {after}")
    print(f"[{target_col}] n_features    : {len(feat_cols)}")

    return df, feat_cols


def make_split_indices(df: pd.DataFrame):
    """Create one fixed train/validation/test split for all tuning trials."""
    idx = np.arange(len(df))

    idx_train_valid, idx_test = train_test_split(
        idx, test_size=TEST_SIZE, random_state=SEED
    )

    valid_ratio_inside = VALID_SIZE / (1.0 - TEST_SIZE)
    idx_train, idx_valid = train_test_split(
        idx_train_valid, test_size=valid_ratio_inside, random_state=SEED
    )

    return idx_train, idx_valid, idx_test


def make_xy_from_indices(
    df: pd.DataFrame,
    feature_cols: list[str],
    target_col: str,
    split_indices: tuple[np.ndarray, np.ndarray, np.ndarray],
):
    idx_train, idx_valid, idx_test = split_indices

    X_train = df.loc[idx_train, feature_cols].copy()
    X_valid = df.loc[idx_valid, feature_cols].copy()
    X_test = df.loc[idx_test, feature_cols].copy()

    y_train = df.loc[idx_train, target_col].copy()
    y_valid = df.loc[idx_valid, target_col].copy()
    y_test = df.loc[idx_test, target_col].copy()

    return X_train, X_valid, X_test, y_train, y_valid, y_test


def make_dmats(X_train, X_valid, X_test, y_train, y_valid, y_test, feature_cols: list[str]):
    dtrain = xgb.DMatrix(X_train, label=y_train, feature_names=feature_cols)
    dvalid = xgb.DMatrix(X_valid, label=y_valid, feature_names=feature_cols)
    dtest = xgb.DMatrix(X_test, label=y_test, feature_names=feature_cols)
    return dtrain, dvalid, dtest


def save_split_tables(X_train, X_valid, X_test, y_train, y_valid, y_test, target_col: str, out_dir: str | Path):
    out_dir = Path(out_dir)
    pd.concat([X_train.reset_index(drop=True), y_train.reset_index(drop=True)], axis=1).to_parquet(
        out_dir / "train_table.parquet", index=False
    )
    pd.concat([X_valid.reset_index(drop=True), y_valid.reset_index(drop=True)], axis=1).to_parquet(
        out_dir / "valid_table.parquet", index=False
    )
    pd.concat([X_test.reset_index(drop=True), y_test.reset_index(drop=True)], axis=1).to_parquet(
        out_dir / "test_table.parquet", index=False
    )


