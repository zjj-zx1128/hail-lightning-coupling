# 3) FEATURE RANKING
# =========================================================
def rank_features_by_full_gain(
    df: pd.DataFrame,
    all_feature_cols: list[str],
    target_col: str,
    split_indices: tuple[np.ndarray, np.ndarray, np.ndarray],
    out_dir: str | Path,
) -> tuple[list[str], str]:
    """Rank all candidate features by gain from a full-feature reference model."""
    print(f"\n[RANK] {target_col}: train full-feature reference model for TopK ranking ...")

    X_train, X_valid, X_test, y_train, y_valid, y_test = make_xy_from_indices(
        df=df,
        feature_cols=all_feature_cols,
        target_col=target_col,
        split_indices=split_indices,
    )
    dtrain, dvalid, _ = make_dmats(
        X_train, X_valid, X_test, y_train, y_valid, y_test, all_feature_cols
    )

    ranking_params = deepcopy(XGB_BASE_PARAMS)
    ranking_params["seed"] = SEED

    ranking_model = train_booster(
        params=ranking_params,
        dtrain=dtrain,
        dvalid=dvalid,
        verbose_eval=False,
    )

    imp_gain = ranking_model.get_score(importance_type="gain")
    df_rank = pd.DataFrame(
        {
            "feature": all_feature_cols,
            "gain": [float(imp_gain.get(c, 0.0)) for c in all_feature_cols],
        }
    )
    df_rank = df_rank.sort_values(
        by=["gain", "feature"], ascending=[False, True]
    ).reset_index(drop=True)
    df_rank["rank"] = np.arange(1, len(df_rank) + 1)

    out_csv = str(Path(out_dir) / f"feature_ranking_gain_full_features_{target_col}.csv")
    df_rank.to_csv(out_csv, index=False, encoding="utf-8-sig")

    print(f"[RANK] Saved: {out_csv}")
    return df_rank["feature"].tolist(), out_csv


# =========================================================
# 4) TRAIN / EVALUATE
# =========================================================
def train_booster(params: dict, dtrain: xgb.DMatrix, dvalid: xgb.DMatrix, verbose_eval=False) -> xgb.Booster:
    evals = [(dtrain, "train"), (dvalid, "valid")]
    return xgb.train(
        params=params,
        dtrain=dtrain,
        num_boost_round=NUM_BOOST_ROUND,
        evals=evals,
        early_stopping_rounds=EARLY_STOPPING_ROUNDS,
        verbose_eval=verbose_eval,
    )


def evaluate_model(
    model: xgb.Booster,
    dtrain: xgb.DMatrix,
    dvalid: xgb.DMatrix,
    dtest: xgb.DMatrix,
    y_train: pd.Series,
    y_valid: pd.Series,
    y_test: pd.Series,
):
    pred_train = predict_with_best(model, dtrain)
    pred_valid = predict_with_best(model, dvalid)
    pred_test = predict_with_best(model, dtest)

    if CLIP_NEGATIVE_PRED:
        pred_train = np.clip(pred_train, 0, None)
        pred_valid = np.clip(pred_valid, 0, None)
        pred_test = np.clip(pred_test, 0, None)

    metrics = {
        "best_iteration": int(get_best_iteration(model)),
        "train": metrics_dict(y_train, pred_train),
        "valid": metrics_dict(y_valid, pred_valid),
        "test": metrics_dict(y_test, pred_test),
    }
    return metrics, pred_train, pred_valid, pred_test


def sensitivity_test(
    target_col: str,
    df: pd.DataFrame,
    ranked_features: list[str],
    all_feature_cols: list[str],
    split_indices: tuple[np.ndarray, np.ndarray, np.ndarray],
    ranking_csv: str | None,
    out_dir: str | Path,
):
    out_dir = Path(out_dir)
    param_combos = make_param_combinations(PARAM_GRID)

    if RUN_TOPK_TEST:
        topk_pairs = normalize_topk_list(TOPK_LIST, len(ranked_features))
    else:
        topk_pairs = [("All", len(all_feature_cols))]
        ranked_features = all_feature_cols

    n_param_trials = len(param_combos)
    n_total_trials = n_param_trials * len(topk_pairs)

    print(f"\n[TUNING] {target_col}: TopK candidates = {topk_pairs}")
    print(f"[TUNING] {target_col}: parameter combos = {n_param_trials}")
    print(f"[TUNING] {target_col}: total trials = {n_total_trials}")

    rows = []
    trial_id = 0
    t0 = time.time()

    for topk_label, actual_k in topk_pairs:
        selected_features = ranked_features[:actual_k]

        topk_feat_csv = out_dir / f"feature_columns_{target_col}_{topk_label}.csv"
        pd.DataFrame({"feature": selected_features}).to_csv(
            topk_feat_csv, index=False, encoding="utf-8-sig"
        )

        X_train, X_valid, X_test, y_train, y_valid, y_test = make_xy_from_indices(
            df=df,
            feature_cols=selected_features,
            target_col=target_col,
            split_indices=split_indices,
        )
        dtrain, dvalid, dtest = make_dmats(
            X_train, X_valid, X_test, y_train, y_valid, y_test, selected_features
        )

        for override in param_combos:
            trial_id += 1
            params = deepcopy(XGB_BASE_PARAMS)
            params.update(override)
            params["seed"] = SEED

            model = train_booster(params, dtrain, dvalid, verbose_eval=VERBOSE_EVAL_TUNING)
            metrics, _, _, _ = evaluate_model(
                model, dtrain, dvalid, dtest, y_train, y_valid, y_test
            )

            train_r2 = metrics["train"]["r2"]
            valid_r2 = metrics["valid"]["r2"]
            test_r2 = metrics["test"]["r2"]

            row = {
                "target": target_col,
                "trial": trial_id,
                "topk_label": topk_label,
                "actual_topk": int(actual_k),
                "n_all_features": int(len(all_feature_cols)),
                "topk_feature_columns_csv": str(topk_feat_csv),
                "feature_ranking_csv": ranking_csv,
                "best_iteration": metrics["best_iteration"],
                "train_r2": train_r2,
                "valid_r2": valid_r2,
                "test_r2": test_r2,
                "train_rmse": metrics["train"]["rmse"],
                "valid_rmse": metrics["valid"]["rmse"],
                "test_rmse": metrics["test"]["rmse"],
                "train_mae": metrics["train"]["mae"],
                "valid_mae": metrics["valid"]["mae"],
                "test_mae": metrics["test"]["mae"],
                "overfit_gap_train_valid": float(train_r2 - valid_r2),
                "abs_valid_test_r2_gap": float(abs(valid_r2 - test_r2)),
            }
            row.update(override)
            rows.append(row)

            if (trial_id % 10 == 0) or (trial_id == 1) or (trial_id == n_total_trials):
                elapsed_min = (time.time() - t0) / 60.0
                print(
                    f"[{target_col}] [{trial_id}/{n_total_trials}] "
                    f"{topk_label} | valid_r2={valid_r2:.4f}, test_r2={test_r2:.4f}, "
                    f"valid_rmse={metrics['valid']['rmse']:.5f}, elapsed={elapsed_min:.1f} min"
                )

    df_trials = pd.DataFrame(rows)

    # This ordering is preserved from the author's latest checked BCC notebook.
    df_trials = df_trials.sort_values(
        by=["valid_r2", "valid_rmse", "abs_valid_test_r2_gap"],
        ascending=[False, True, True],
    ).reset_index(drop=True)

    out_csv = out_dir / f"tuning_results_{target_col}.csv"
    df_trials.to_csv(out_csv, index=False, encoding="utf-8-sig")

    best_row = df_trials.iloc[0].to_dict()
    best_params = deepcopy(XGB_BASE_PARAMS)
    for key in PARAM_GRID:
        best_params[key] = best_row[key]
    best_params["seed"] = SEED

    selected_topk_label = str(best_row["topk_label"])
    selected_topk_n = int(best_row["actual_topk"])
    selected_features = ranked_features[:selected_topk_n]

    best_json = {
        "target": target_col,
        "selection_rule": "max valid_r2, then min valid_rmse, then min abs_valid_test_r2_gap",
        "run_topk_test": RUN_TOPK_TEST,
        "topk_list": TOPK_LIST,
        "selected_topk_label": selected_topk_label,
        "selected_topk_n": selected_topk_n,
        "n_param_combinations": int(n_param_trials),
        "n_total_trials": int(n_total_trials),
        "n_all_features": int(len(all_feature_cols)),
        "best_row": best_row,
        "best_params": best_params,
        "selected_feature_columns": selected_features,
        "feature_ranking_csv": ranking_csv,
        "tuning_results_csv": str(out_csv),
    }
    with open(out_dir / f"best_params_{target_col}.json", "w", encoding="utf-8") as f:
        json.dump(best_json, f, ensure_ascii=False, indent=2)

    print(f"\n[BEST] {target_col}")
    print(json.dumps(best_json, ensure_ascii=False, indent=2))

    return best_params, selected_features, selected_topk_label, selected_topk_n, df_trials


def train_one_target(df: pd.DataFrame, all_feature_cols: list[str], target_col: str, out_dir: str | Path):
    out_dir = Path(out_dir)
    safe_mkdir(out_dir)

    all_feat_csv = out_dir / "feature_columns_all_candidates.csv"
    pd.DataFrame({"feature": all_feature_cols}).to_csv(
        all_feat_csv, index=False, encoding="utf-8-sig"
    )

    split_indices = make_split_indices(df)

    if RUN_SENSITIVITY_TEST and RUN_TOPK_TEST:
        ranked_features, ranking_csv = rank_features_by_full_gain(
            df=df,
            all_feature_cols=all_feature_cols,
            target_col=target_col,
            split_indices=split_indices,
            out_dir=out_dir,
        )
    else:
        ranked_features = all_feature_cols
        ranking_csv = None

    if RUN_SENSITIVITY_TEST:
        best_params, selected_features, selected_topk_label, selected_topk_n, _ = sensitivity_test(
            target_col=target_col,
            df=df,
            ranked_features=ranked_features,
            all_feature_cols=all_feature_cols,
            split_indices=split_indices,
            ranking_csv=ranking_csv,
            out_dir=out_dir,
        )
    else:
        best_params = deepcopy(XGB_BASE_PARAMS)
        best_params["seed"] = SEED
        selected_features = all_feature_cols
        selected_topk_label = "All"
        selected_topk_n = len(selected_features)
        with open(out_dir / f"best_params_{target_col}.json", "w", encoding="utf-8") as f:
            json.dump(
                {
                    "target": target_col,
                    "selection_rule": "RUN_SENSITIVITY_TEST=False; use XGB_BASE_PARAMS and all features",
                    "run_topk_test": False,
                    "selected_topk_label": selected_topk_label,
                    "selected_topk_n": selected_topk_n,
                    "best_params": best_params,
                },
                f,
                ensure_ascii=False,
                indent=2,
            )

    selected_feat_csv = out_dir / "feature_columns.csv"
    pd.DataFrame({"feature": selected_features}).to_csv(
        selected_feat_csv, index=False, encoding="utf-8-sig"
    )

    X_train, X_valid, X_test, y_train, y_valid, y_test = make_xy_from_indices(
        df=df,
        feature_cols=selected_features,
        target_col=target_col,
        split_indices=split_indices,
    )
    save_split_tables(
        X_train, X_valid, X_test, y_train, y_valid, y_test, target_col, out_dir
    )

    dtrain, dvalid, dtest = make_dmats(
        X_train, X_valid, X_test, y_train, y_valid, y_test, selected_features
    )

    print(
        f"\n[FINAL TRAIN] {target_col} | {selected_topk_label} "
        f"({selected_topk_n} features) ..."
    )
    final_model = train_booster(
        best_params, dtrain, dvalid, verbose_eval=VERBOSE_EVAL_FINAL
    )

    metrics, pred_train, pred_valid, pred_test = evaluate_model(
        final_model, dtrain, dvalid, dtest, y_train, y_valid, y_test
    )

    metrics_out = {
        "model_name": MODEL_NAME,
        "target": target_col,
        "best_iteration": metrics["best_iteration"],
        "train": metrics["train"],
        "valid": metrics["valid"],
        "test": metrics["test"],
        "n_all_features": int(len(all_feature_cols)),
        "selected_topk_label": selected_topk_label,
        "selected_topk_n": int(selected_topk_n),
        "n_features": int(len(selected_features)),
        "all_candidate_feature_columns_csv": str(all_feat_csv),
        "feature_columns_csv": str(selected_feat_csv),
        "feature_ranking_csv": ranking_csv,
        "feature_hist": str(FEATURE_HIST),
        "label_strict": str(LABEL_STRICT),
        "run_sensitivity_test": RUN_SENSITIVITY_TEST,
        "run_topk_test": RUN_TOPK_TEST,
        "topk_list": TOPK_LIST,
        "final_params": best_params,
    }

    with open(out_dir / "metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics_out, f, ensure_ascii=False, indent=2)

    final_model.save_model(str(out_dir / "xgb_model.json"))

    imp_gain = final_model.get_score(importance_type="gain")
    df_imp = pd.DataFrame(
        {"feature": list(imp_gain.keys()), "gain": list(imp_gain.values())}
    ).sort_values("gain", ascending=False)
    df_imp.to_csv(
        out_dir / "feature_importance_gain.csv", index=False, encoding="utf-8-sig"
    )

    for split_name, X_split, y_split, pred_split in (
        ("train", X_train, y_train, pred_train),
        ("valid", X_valid, y_valid, pred_valid),
        ("test", X_test, y_test, pred_test),
    ):
        df_pred = X_split.copy()
        df_pred[target_col] = y_split.values
        df_pred["pred"] = pred_split
        df_pred.to_parquet(out_dir / f"pred_{split_name}.parquet", index=False)

    print(f"\n[DONE] {target_col}")
    print(json.dumps(metrics_out, ensure_ascii=False, indent=2))

    return final_model, metrics_out, selected_features


